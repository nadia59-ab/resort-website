export type AdminLabel = keyof typeof labels.en | keyof typeof extraLabels.en | "mediaNav" | "completionNotDue";

export function adminLabel(language: AdminLanguage, key: AdminLabel) {
  if (key === "mediaNav") return ({ ar: "الوسائط", en: "Media", ru: "Медиа", de: "Medien" })[language];
  if (key === "completionNotDue") return ({
    ar: "لا يمكن إكمال الحجز قبل تاريخ المغادرة.",
    en: "A booking cannot be completed before its check-out date.",
    ru: "Нельзя завершить бронирование до даты выезда.",
    de: "Eine Buchung kann erst am Abreisetag oder danach abgeschlossen werden.",
  })[language];
  return extraLabels[language][key] ?? labels[language][key as keyof typeof labels.en];
}
