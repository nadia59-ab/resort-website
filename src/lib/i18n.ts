export function translate(language: Language, english: string, arabic?: string) {
  if (language === "ar") return arabic ?? english;
  if (language === "ru") return RU[english] ?? english;
  if (language === "de") return DE[english] ?? english;
  return english;
}

export function translateWithValues(language: Language, english: string, arabic: string, values: Record<string, string | number>) {
  let translated = translate(language, english, arabic);
  for (const [key, value] of Object.entries(values)) {
    translated = translated.replaceAll(`{${key}}`, String(value));
  }
  return translated;
}

export function translateMessage(language: Language, english: string) {
  if (language === "ar") return AR_ERRORS[english] ?? english;
  return translate(language, english);
}

export function isLanguage(value: unknown): value is Language {
  return typeof value === "string" && LANGUAGES.includes(value as Language);
}
