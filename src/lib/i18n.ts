export const LANGUAGES = ["en", "ar", "ru", "de"] as const;
export type Language = (typeof LANGUAGES)[number];

export function localizedContent(
  language: Language,
  values: { en: string; ar?: string | null; ru?: string | null; de?: string | null },
) {
  const translated = language === "ar"
    ? values.ar
    : language === "ru"
      ? values.ru
      : language === "de"
        ? values.de
        : values.en;
  return translated?.trim() || values.en;
}

